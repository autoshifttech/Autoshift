export function adminTranslate(locale: string, text: string): string {
  const row = T[text];
  if (!row) return text;
  if (locale === "pt") return row[0];
  if (locale === "es") return row[1];
  if (locale === "ko") return row[2];
  return text;
}

/** `const tr = useAdminT(); tr("Payments")` → the current language. */
export function useAdminT() {
  const locale = useLocale();
  return (text: string) => adminTranslate(locale, text);
}
